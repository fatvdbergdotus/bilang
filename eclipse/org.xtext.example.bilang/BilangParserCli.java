package org.xtext.example.bilang.cli;

import com.google.inject.Injector;

import org.eclipse.emf.common.util.URI;
import org.eclipse.emf.ecore.EAttribute;
import org.eclipse.emf.ecore.EObject;
import org.eclipse.emf.ecore.EReference;
import org.eclipse.emf.ecore.resource.Resource;
import org.eclipse.xtext.resource.XtextResource;
import org.eclipse.xtext.resource.XtextResourceSet;
import org.eclipse.xtext.util.CancelIndicator;
import org.eclipse.xtext.validation.CheckMode;
import org.eclipse.xtext.validation.IResourceValidator;
import org.eclipse.xtext.validation.Issue;
import org.xtext.example.bilang.BilangStandaloneSetup;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.StringJoiner;

/**
 * BilangParserCli
 *
 * Responsibilities:
 * 1. Load the generated Bilang Xtext parser.
 * 2. Parse a .bilang file.
 * 3. Validate the parsed model.
 * 4. Seriialze the EMF model to JSON.
 *
 * Usage:
 * java -cp "<XTEXT_CLASSPATH>" \
 *   org.xtext.example.bilang.cli.BilangParserCli example.bilang
 *
 * Standard output contains JSON.
 * Standard error contains diagnostic messages.
 */
public final class BilangParserCli {

    private BilangParserCli() {
    }

    public static void main(String[] args) {
        if (args.length != 1) {
            System.err.println(
                "Usage: BilangParserCli <file.bilang>"
            );
            System.exit(2);
        }

        try {
            Map<String, Object> result = parseFile(args[0]);

            System.out.println(Json.write(result));

            if (!Boolean.TRUE.equals(result.get("valid"))) {
                System.exit(1);
            }

        } catch (Exception exception) {
            Map<String, Object> result =
                new LinkedHashMap<>();

            result.put("valid", false);
            result.put(
                "errors",
                List.of(
                    exception.getClass().getSimpleName()
                    + ": "
                    + String.valueOf(exception.getMessage())
                )
            );

            System.err.println(
                Json.write(result)
            );

            System.exit(1);
        }
    }

    /**
     * Parse and validate a Bilang source file.
     */
    public static Map<String, Object> parseFile(
            String fileName) throws Exception {

        Path file = Path.of(fileName)
                        .toAbsolutePath()
                        .normalize();

        if (!java.nio.file.Files.isRegularFile(file)) {
            throw new IllegalArgumentException(
                "Bilang file does not exist: " + file
            );
        }

        /*
         * Initialize the generated Xtext language.
         *
         * This class is generated by Xtext. If your project
         * uses a different setup class name, replace it here.
         */
        Injector injector =
            new BilangStandaloneSetup()
                .createInjectorAndDoEMFRegistration();

        /*
         * Create a resource set using the Xtext runtime.
         */
        XtextResourceSet resourceSet =
            injector.getInstance(XtextResourceSet.class);

        resourceSet.addLoadOption(
            XtextResource.OPTION_RESOLVE_ALL,
            Boolean.TRUE
        );

        /*
         * Load and parse the source file.
         */
        URI uri = URI.createFileURI(file.toString());

        Resource resource =
            resourceSet.getResource(uri, true);

        /*
         * Collect parser errors and validation errors.
         */
        List<String> errors = new ArrayList<>();
        List<String> warnings = new ArrayList<>();

        for (Resource.Diagnostic diagnostic
                : resource.getErrors()) {

            errors.add(
                formatDiagnostic(
                    diagnostic.getLine(),
                    diagnostic.getColumn(),
                    diagnostic.getMessage()
                )
            );
        }

        IResourceValidator validator =
            injector.getInstance(
                IResourceValidator.class
            );

        List<Issue> issues = validator.validate(
            resource,
            CheckMode.ALL,
            CancelIndicator.NullImpl
        );

        for (Issue issue : issues) {
            String message = formatDiagnostic(
                issue.getLineNumber() == null
                    ? -1 : issue.getLineNumber(),
                issue.getColumn() == null
                    ? -1 : issue.getColumn(),
                issue.getMessage()
            );

            switch (issue.getSeverity()) {
                case ERROR:
                    if (!errors.contains(message)) {
                        errors.add(message);
                    }
                    break;

                case WARNING:
                    warnings.add(message);
                    break;

                default:
                    // Informational diagnostics are omitted.
                    break;
            }
        }

        /*
         * Do not serialize or execute an invalid program.
         */
        Map<String, Object> result =
            new LinkedHashMap<>();

        result.put("valid", errors.isEmpty());
        result.put("source", file.toString());
        result.put("errors", errors);
        result.put("warnings", warnings);

        if (!errors.isEmpty()) {
            result.put("elements", List.of());
            return result;
        }

        /*
         * Serialize each root object in the EMF model.
         */
        List<Object> elements = new ArrayList<>();

        for (EObject object : resource.getContents()) {
            elements.add(serialize(object));
        }

        result.put("elements", elements);

        return result;
    }

    private static String formatDiagnostic(
            int line,
            int column,
            String message) {

        return line + ":" + column + " " + message;
    }

    /**
     * Convert an EMF object into a JSON-compatible map.
     *
     * The result includes:
     * - $type: generated EClass name
     * - EAttributes: scalar or list-valued attributes
     * - Containment EReferences: recursively serialized objects
     * - Non-containment EReferences: lightweight references
     */
    private static Map<String, Object> serialize(
            EObject object) {

        Map<String, Object> result =
            new LinkedHashMap<>();

        result.put(
            "$type",
            object.eClass().getName()
        );

        /*
         * Serialize attributes, including inherited features.
         */
        for (EAttribute attribute
                : object.eClass().getEAllAttributes()) {

            if (attribute.isTransient()
                    || attribute.isDerived()) {
                continue;
            }

            Object value = object.eGet(attribute);

            if (value == null) {
                continue;
            }

            result.put(
                attribute.getName(),
                normalizeValue(value)
            );
        }

        /*
         * Serialize model references.
         */
        for (EReference reference
                : object.eClass().getEAllReferences()) {

            if (reference.isTransient()
                    || reference.isDerived()) {
                continue;
            }

            Object value = object.eGet(reference);

            if (value == null) {
                continue;
            }

            if (reference.isContainment()) {

                if (value instanceof Collection<?> values) {
                    List<Object> serialized =
                        new ArrayList<>();

                    for (Object item : values) {
                        if (item instanceof EObject child) {
                            serialized.add(
                                serialize(child)
                            );
                        } else {
                            serialized.add(
                                normalizeValue(item)
                            );
                        }
                    }

                    result.put(
                        reference.getName(),
                        serialized
                    );

                } else if (value instanceof EObject child) {
                    result.put(
                        reference.getName(),
                        serialize(child)
                    );
                }

            } else {

                /*
                 * Represent cross-references without recursively
                 * serializing the target and creating cycles.
                 */
                if (value instanceof Collection<?> values) {
                    List<Object> references =
                        new ArrayList<>();

                    for (Object item : values) {
                        if (item instanceof EObject target) {
                            references.add(
                                serializeReference(target)
                            );
                        }
                    }

                    result.put(
                        reference.getName(),
                        references
                    );

                } else if (value instanceof EObject target) {
                    result.put(
                        reference.getName(),
                        serializeReference(target)
                    );
                }
            }
        }

        return result;
    }

    /**
     * Serialize a cross-reference without traversing the target.
     */
    private static Map<String, Object> serializeReference(
            EObject target) {

        Map<String, Object> reference =
            new LinkedHashMap<>();

        reference.put(
            "$refType",
            target.eClass().getName()
        );

        String name = findName(target);

        if (name != null) {
            reference.put("$name", name);
        }

        return reference;
    }

    /**
     * Try to identify an object by its common name or alias
     * attribute. This is useful for workflow references.
     */
    private static String findName(EObject object) {

        for (EAttribute attribute
                : object.eClass().getEAllAttributes()) {

            String featureName = attribute.getName();

            if (!"name".equals(featureName)
                    && !"alias".equals(featureName)
                    && !"id".equals(featureName)) {
                continue;
            }

            Object value = object.eGet(attribute);

            if (value != null) {
                return normalizeValue(value).toString();
            }
        }

        return null;
    }

    /**
     * Convert EMF attribute values to JSON-compatible values.
     */
    private static Object normalizeValue(Object value) {

        if (value == null) {
            return null;
        }

        if (value instanceof String
                || value instanceof Number
                || value instanceof Boolean) {
            return value;
        }

        if (value instanceof Enum<?> enumValue) {
            return enumValue.name();
        }

        if (value instanceof Collection<?> collection) {
            List<Object> result = new ArrayList<>();

            for (Object item : collection) {
                result.add(normalizeValue(item));
            }

            return result;
        }

        return value.toString();
    }

    /**
     * Minimal JSON serializer; avoids an additional JSON library.
     */
    private static final class Json {

        private Json() {
        }

        static String write(Object value) {

            if (value == null) {
                return "null";
            }

            if (value instanceof String string) {
                return quote(string);
            }

            if (value instanceof Number
                    || value instanceof Boolean) {
                return value.toString();
            }

            if (value instanceof Map<?, ?> map) {
                StringJoiner joiner =
                    new StringJoiner(",", "{", "}");

                for (Map.Entry<?, ?> entry
                        : map.entrySet()) {

                    joiner.add(
                        quote(String.valueOf(entry.getKey()))
                        + ":"
                        + write(entry.getValue())
                    );
                }

                return joiner.toString();
            }

            if (value instanceof Iterable<?> iterable) {
                StringJoiner joiner =
                    new StringJoiner(",", "[", "]");

                for (Object item : iterable) {
                    joiner.add(write(item));
                }

                return joiner.toString();
            }

            return quote(value.toString());
        }

        private static String quote(String value) {

            StringBuilder builder =
                new StringBuilder("\"");

            for (int i = 0; i < value.length(); i++) {
                char c = value.charAt(i);

                switch (c) {
                    case '"' ->
                        builder.append("\\\"");
                    case '\\' ->
                        builder.append("\\\\");
                    case '\b' ->
                        builder.append("\\b");
                    case '\f' ->
                        builder.append("\\f");
                    case '\n' ->
                        builder.append("\\n");
                    case '\r' ->
                        builder.append("\\r");
                    case '\t' ->
                        builder.append("\\t");

                    default -> {
                        if (c < 0x20) {
                            builder.append(
                                String.format(
                                    "\\u%04x",
                                    (int) c
                                )
                            );
                        } else {
                            builder.append(c);
                        }
                    }
                }
            }

            return builder.append('"').toString();
        }
    }
}
